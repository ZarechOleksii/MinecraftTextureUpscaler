"""Generate the documentation of the presets: a page per preset with screenshots, an index and comparison sheets.

Usage: regen4x-docs [--samples DIR --out DIR] [--scale N] [--also N ...] [--presets FILE ...]

Without --samples / --out it builds the standard set, if its sample folder exists:
  samples/free     ->  docs/presets          textures that may be redistributed
Use --samples and --out for any other folder of textures.

A sample folder holds 16x16 PNGs and a ``samples.toml``:

    title = "Free samples"                 # optional: heading of the index
    note  = "Where these come from ..."    # optional: a paragraph under it
    [[sample]]
    file     = "bricks.png"                # relative to this folder
    kind     = "block"                     # block | item: which sheet it goes on
    geometry = "straight brick lines"      # what it is there to show
    credit   = "Author, CC0"               # shown in the index

Output: README.md (index, sheets, credits), <PRESET>.md for every preset (what it changes against its parent, all its
settings, screenshots) and img/ (the sheets, and img/<PRESET>/blocks.png and items.png: original | parent | preset).
The sheets and those images use --scale (default 4: 16px -> 64px); each preset page also shows the other scales of
--also (default 2 and 8: 32px and 128px) as blocks_x2.png, blocks_x8.png ...
Every file it writes starts with a marker line; the next run removes the marker files it finds, so presets that no
longer exist leave nothing behind.
"""

import argparse
import shutil
import tomllib
from collections.abc import Sequence
from dataclasses import dataclass, fields
from pathlib import Path

from PIL import Image, ImageDraw

from regen4x import presets
from regen4x.params import RegenParams
from regen4x.tools.run_pack import MAX_SCALE, MIN_SCALE
from regen4x.upscaler import regen4x

MARKER = "<!-- Generated by regen4x-docs: do not edit. Change presets.toml or the sample manifest and run it again. -->"
DEFAULT_SETS = (("samples/free", "docs/presets"),)
KINDS = {"block": "Blocks", "item": "Items"}
CELL, GAP, HEAD, LABEL_W = 128, 8, 30, 220
GREY = (70, 70, 70, 255)
PER_SHEET = 6  #: presets per comparison sheet
TILE = 16

_MANIFEST_KEYS = {"title", "note", "sample"}
_SAMPLE_KEYS = {"file", "kind", "geometry", "credit"}


@dataclass(frozen=True, slots=True)
class Sample:
    name: str
    kind: str
    geometry: str
    credit: str
    image: Image.Image


@dataclass(frozen=True, slots=True)
class SampleSet:
    title: str
    note: str
    samples: tuple[Sample, ...]

    def of_kind(self, kind: str) -> list[Sample]:
        return [s for s in self.samples if s.kind == kind]


def load_samples(folder: Path) -> SampleSet:
    """The samples listed in ``folder/samples.toml``."""
    manifest = folder / "samples.toml"
    try:
        doc = tomllib.loads(manifest.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as e:
        raise ValueError(f"{manifest}: {getattr(e, 'strerror', None) or e}") from e
    unknown = sorted(set(doc) - _MANIFEST_KEYS)
    if unknown:
        raise ValueError(f"{manifest}: unknown key(s) {', '.join(map(repr, unknown))}")
    samples: list[Sample] = []
    for i, spec in enumerate(doc.get("sample", []), 1):
        where = f"{manifest}: sample {i}"
        unknown = sorted(set(spec) - _SAMPLE_KEYS)
        if unknown:
            raise ValueError(f"{where}: unknown key(s) {', '.join(map(repr, unknown))}")
        if "file" not in spec or spec.get("kind") not in KINDS:
            raise ValueError(f"{where}: needs a 'file' and a 'kind' ({' or '.join(KINDS)})")
        path = folder / spec["file"]
        if not path.is_file():
            raise ValueError(f"{where}: {path} does not exist")
        with Image.open(path) as f:
            image = f.convert("RGBA")
        if image.size != (TILE, TILE):
            raise ValueError(f"{where}: {path.name} is {image.width}x{image.height}, samples must be 16x16")
        if any(s.name == path.stem for s in samples):
            raise ValueError(f"{where}: the name {path.stem!r} is used twice")
        samples.append(Sample(path.stem, spec["kind"], spec.get("geometry", ""), spec.get("credit", ""), image))
    if not samples:
        raise ValueError(f"{manifest}: no [[sample]] entries")
    return SampleSet(str(doc.get("title", "Samples")), str(doc.get("note", "")), tuple(samples))


class Renderer:
    """Upscales samples with presets; every (sample, preset) pair once."""

    def __init__(self, book: presets.Book, scale: int) -> None:
        self.book = book
        self.scale = scale
        self._cache: dict[tuple[str, str], Image.Image] = {}

    def render(self, sample: Sample, preset: str | None) -> Image.Image:
        """``sample`` upscaled with ``preset`` (``None`` = the RegenParams defaults)."""
        key = (sample.name, preset or "")
        if key not in self._cache:
            params = RegenParams() if preset is None else self.book.preset(preset)
            rel = f"samples/textures/{sample.kind}/{sample.name}.png"
            self._cache[key] = regen4x(sample.image, params, seed=presets.seed_for(rel), scale=self.scale)
        return self._cache[key]


def tile(im: Image.Image) -> Image.Image:
    cell = Image.new("RGBA", (CELL, CELL), GREY)
    cell.alpha_composite(im.convert("RGBA").resize((CELL, CELL), Image.Resampling.NEAREST))
    return cell


def compose_sheet(headers: Sequence[str], rows: Sequence[tuple[str, str, Sequence[Image.Image]]]) -> Image.Image:
    """A grid: one row per (label, caption, tiles), one column per header."""
    width = LABEL_W + len(headers) * (CELL + GAP)
    sheet = Image.new("RGBA", (width, HEAD + len(rows) * (CELL + GAP) + GAP), GREY)
    draw = ImageDraw.Draw(sheet)
    for c, header in enumerate(headers):
        draw.text((LABEL_W + c * (CELL + GAP), 10), header, fill="white")
    for r, (label, caption, tiles) in enumerate(rows):
        y = HEAD + r * (CELL + GAP)
        draw.text((8, y + CELL // 2 - 14), label[:34], fill="white")
        draw.text((8, y + CELL // 2 + 2), caption[:34], fill=(190, 190, 190, 255))
        for c, im in enumerate(tiles):
            sheet.paste(tile(im), (LABEL_W + c * (CELL + GAP), y))
    return sheet


def save(im: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path)


def option_table(params: RegenParams, base: RegenParams, base_label: str, name: str) -> list[str]:
    rows = [(f.name, getattr(base, f.name), getattr(params, f.name)) for f in fields(RegenParams)]
    changed = [f"| `{option}` | `{old!r}` | `{new!r}` |" for option, old, new in rows if old != new]
    if not changed:
        return ["Nothing: it sets the same options as its parent."]
    return [f"| option | {base_label} | {name} |", "|---|---|---|", *changed]


STATUS_MEANING = {
    "base": "a building block that other presets extend; not meant to be picked directly",
    "stable": "ready to use; the newest profile release ships it",
    "experimental": "may change or be removed; not used by any profile",
    "superseded": "replaced by a newer version, kept so older packs can be rebuilt",
}


def rules_using(book: presets.Book, name: str) -> list[str]:
    seen: list[str] = []
    for profile in book.profiles.values():
        for rule in profile.rules:
            if rule.preset == name:
                keep = ", then restores lost opaque pixels" if rule.keep_opaque else ""
                line = f"- profile `{profile.name}`: {rule.when}{keep}"
                if line not in seen:
                    seen.append(line)
    return seen


def size_label(scale: int) -> str:
    return f"x{scale}: 16px to {16 * scale}px"


def preset_page(book: presets.Book, name: str, kinds: Sequence[str], scale: int = 4, others: Sequence[int] = ()) -> str:
    params = book.preset(name)
    parent = book.parents[name]
    base = RegenParams() if parent is None else book.preset(parent)
    base_label = "defaults" if parent is None else parent
    children = [n for n, p in book.parents.items() if p == name]
    lines = [MARKER, "", f"# {name}", "", book.notes.get(name, "").strip(), ""]
    if status := book.statuses.get(name):
        lines.append(f"Status: **{status}** ({STATUS_MEANING[status]})  ")
    if changelog := book.changelogs.get(name):
        lines.append(f"Changes in this version: {changelog}  ")
    lines.append(f"Based on: {'the `RegenParams` defaults' if parent is None else f'[{parent}]({parent}.md)'}  ")
    if children:
        lines.append("Built on this: " + ", ".join(f"[{c}]({c}.md)" for c in children) + "  ")
    used = rules_using(book, name)
    lines += [
        "",
        "Used by:" if used else "Not used by any built-in profile (pick it with `--blocks`, `--items` or `--use`).",
        *used,
    ]
    lines += [
        "",
        "## What it changes",
        "",
        f"Compared with {base_label}:",
        "",
        *option_table(params, base, base_label, name),
    ]
    if kinds:
        lines += ["", "## Examples", "", f"Original | {base_label} | {name}."]
    for kind in kinds:
        lines += ["", f"### {KINDS[kind]}"]
        for s in sorted([scale, *others]):
            suffix = "" if s == scale else f"_x{s}"
            note = " (default)" if s == scale else ""
            lines += [
                "",
                f"{size_label(s)}{note}",
                "",
                f"![{name} on {KINDS[kind].lower()}, x{s}](img/{name}/{kind}s{suffix}.png)",
            ]
    lines += [
        "",
        "## All settings",
        "",
        "Every option that differs from the `RegenParams` default, and the preset that set it:",
        "",
    ]
    defaults = RegenParams()
    lines.append("```text")
    for f in fields(RegenParams):
        value = getattr(params, f.name)
        if value != getattr(defaults, f.name):
            lines.append(f"{f.name} = {value!r}   [{book.origins[name].get(f.name, name)}]")
    lines += ["```", ""]
    return "\n".join(lines)


def index_page(book: presets.Book, samples: SampleSet, sheets: dict[str, list[tuple[str, list[str]]]]) -> str:
    lines = [MARKER, "", f"# Presets: {samples.title}", ""]
    if samples.note:
        lines += [samples.note.strip(), ""]
    lines += [
        "Generated by `regen4x-docs` from `presets.toml` and the sample manifest. "
        "Each preset page lists what it changes "
        "against its parent and shows the samples before and after.",
        "",
        "## Presets",
        "",
        "| preset | status | based on | summary |",
        "|---|---|---|---|",
    ]
    for name, parent in book.parents.items():
        summary = " ".join(book.notes.get(name, "").split())
        based = "defaults" if parent is None else f"[{parent}]({parent}.md)"
        lines.append(f"| [{name}]({name}.md) | {book.statuses.get(name, '')} | {based} | {summary} |")
    lines += ["", "## Profiles", "", "Which preset a texture gets (first matching rule wins):", ""]
    lines += [f"- `{alias}`: another name for `{target}`" for alias, target in book.aliases.items()]
    for pname, profile in book.profiles.items():
        lines.append(f"- `{pname}`" + (f": {book.notes[pname]}" if pname in book.notes else ""))
        lines.extend(
            f"  - {r.when}: [{r.preset}]({r.preset}.md)" + (" (keep opaque)" if r.keep_opaque else "")
            for r in profile.rules
        )
    lines += ["", "## Comparison sheets", ""]
    for kind, files in sheets.items():
        lines += [f"### {KINDS[kind]}", ""]
        for file, names in files:
            lines += [
                f"Original, then {', '.join(names)}:",
                "",
                f"![{KINDS[kind]}: {', '.join(names)}](img/{file})",
                "",
            ]
    lines += ["## Samples", "", "| texture | kind | shows | credit |", "|---|---|---|---|"]
    lines += [f"| {s.name} | {s.kind} | {s.geometry} | {s.credit} |" for s in samples.samples]
    lines.append("")
    return "\n".join(lines)


def clean(out: Path) -> None:
    """Remove what an earlier run wrote (marker pages and img/), nothing else."""
    for page in out.glob("*.md"):
        if page.read_text(encoding="utf-8").startswith(MARKER):
            page.unlink()
    shutil.rmtree(out / "img", ignore_errors=True)


def build_docs(samples: SampleSet, out: Path, book: presets.Book, scale: int, also: Sequence[int] = ()) -> list[Path]:
    """Write the documentation into ``out``; returns the pages written.

    The sheets and ``img/<preset>/<kind>s.png`` use ``scale``; ``img/<preset>/<kind>s_x<N>.png`` is added for every
    other scale in ``also``.
    """
    renderer = Renderer(book, scale)
    others = [s for s in dict.fromkeys(also) if s != scale]
    extra = {s: Renderer(book, s) for s in others}
    clean(out)
    out.mkdir(parents=True, exist_ok=True)
    kinds = [k for k in KINDS if samples.of_kind(k)]
    pages: list[Path] = []
    for name, parent in book.parents.items():
        for kind in kinds:
            rows = [
                (s.name, s.geometry, [s.image, renderer.render(s, parent), renderer.render(s, name)])
                for s in samples.of_kind(kind)
            ]
            headers = ["original", "defaults" if parent is None else parent, name]
            save(compose_sheet(headers, rows), out / "img" / name / f"{kind}s.png")
            for s, other in extra.items():
                rows = [
                    (s_.name, s_.geometry, [s_.image, other.render(s_, parent), other.render(s_, name)])
                    for s_ in samples.of_kind(kind)
                ]
                save(compose_sheet(headers, rows), out / "img" / name / f"{kind}s_x{s}.png")
        page = out / f"{name}.md"
        page.write_text(preset_page(book, name, kinds, scale, others), encoding="utf-8")
        pages.append(page)
    sheets: dict[str, list[tuple[str, list[str]]]] = {}
    names = list(book.presets)
    for kind in kinds:
        for n, start in enumerate(range(0, len(names), PER_SHEET), 1):
            chunk = names[start : start + PER_SHEET]
            rows = [
                (s.name, s.geometry, [s.image, *(renderer.render(s, p) for p in chunk)]) for s in samples.of_kind(kind)
            ]
            file = f"sheet_{kind}s_{n}.png"
            save(compose_sheet(["original", *chunk], rows), out / "img" / file)
            sheets.setdefault(kind, []).append((file, chunk))
    index = out / "README.md"
    index.write_text(index_page(book, samples, sheets), encoding="utf-8")
    return [index, *pages]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--samples", type=Path, metavar="DIR", help="folder with samples.toml and the PNGs")
    parser.add_argument("--out", type=Path, metavar="DIR", help="where to write the documentation")
    parser.add_argument("--scale", type=int, default=4, metavar="N", help=f"{MIN_SCALE}..{MAX_SCALE}, default 4")
    parser.add_argument(
        "--also",
        type=int,
        nargs="*",
        default=[2, 8],
        metavar="N",
        help="more scales to show on the preset pages (default 2 8; none: --also with no value)",
    )
    parser.add_argument(
        "--presets", action="append", default=[], type=Path, metavar="FILE", help="extra presets (TOML)"
    )
    args = parser.parse_args(argv)
    if (args.samples is None) != (args.out is None):
        parser.error("--samples and --out go together")
    if not MIN_SCALE <= args.scale <= MAX_SCALE:
        parser.error(f"scale must be {MIN_SCALE}..{MAX_SCALE}, not {args.scale}")
    for s in args.also:
        if not MIN_SCALE <= s <= MAX_SCALE:
            parser.error(f"--also scales must be {MIN_SCALE}..{MAX_SCALE}, not {s}")
    jobs = [(args.samples, args.out)] if args.samples else [(Path(s), Path(o)) for s, o in DEFAULT_SETS]
    try:
        book = presets.load_book(args.presets)
        for src, out in jobs:
            if not (src / "samples.toml").is_file():
                if args.samples:
                    parser.error(f"{src / 'samples.toml'} does not exist")
                print(f"skipped {src} (no samples.toml)")
                continue
            written = build_docs(load_samples(src), out, book, args.scale, args.also)
            print(f"{src} -> {out}: {len(written)} pages")
    except (KeyError, ValueError) as e:
        return parser.error(str(e.args[0]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
